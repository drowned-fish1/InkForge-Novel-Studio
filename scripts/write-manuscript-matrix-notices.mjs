import { readFile, readdir, mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Keep the licenses alongside the bundled renderer in packaged applications.
const roots = ["mammoth", "react-data-grid"];
const taskRoot = fileURLToPath(new URL("..", import.meta.url));
const seen = new Set();
const sections = [];
const normalizeNotice = (value) => value.replace(/[\t ]+$/gmu, "").trim();
async function collect(name, from) {
  const require = createRequire(join(from, "package.json"));
  let root;
  try {
    root = dirname(require.resolve(`${name}/package.json`));
  } catch {
    root = dirname(require.resolve(name));
    while (root !== dirname(root)) {
      try {
        if (JSON.parse(await readFile(join(root, "package.json"), "utf8")).name === name) break;
      } catch {
        /* Continue to package root. */
      }
      root = dirname(root);
    }
  }
  const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) return;
  seen.add(key);
  const licenseNames = (await readdir(root)).filter((entry) => /^(?:licen[cs]e|copying|notice)(?:\.|$)/iu.test(entry));
  if (!licenseNames.length) {
    const readme = (await readdir(root)).find((entry) => /^readme(?:\.|$)/iu.test(entry));
    if (!readme) throw new Error(`No license file found for ${key}`);
    const content = await readFile(join(root, readme), "utf8");
    if (!/^#+\s*license/imu.test(content)) throw new Error(`No license section found for ${key}`);
    sections.push(
      normalizeNotice(
        `${key} (${pkg.license ?? "See license below"})\n${content.slice(content.search(/^#+\s*license/imu))}`
      )
    );
  }
  const notices = await Promise.all(licenseNames.map((entry) => readFile(join(root, entry), "utf8")));
  if (notices.length) {
    sections.push(normalizeNotice(`${key} (${pkg.license ?? "See license below"})\n${notices.join("\n")}`));
  }
  for (const dependency of Object.keys(pkg.dependencies ?? {}).sort()) await collect(dependency, root);
}
for (const name of roots) await collect(name, resolve(taskRoot, "apps/desktop"));
await mkdir(join(taskRoot, "apps/desktop/public"), { recursive: true });
await writeFile(
  join(taskRoot, "apps/desktop/public/manuscript-matrix-notices.txt"),
  `Third-party notices for manuscript migration and whole-book matrix\nGenerated by scripts/write-manuscript-matrix-notices.mjs from installed packages.\n\n${sections.join("\n\n============================================================\n\n")}\n`
);
console.log(`Wrote notices for ${seen.size} packages.`);
